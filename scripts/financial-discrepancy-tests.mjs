import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const load=(name,requireFn)=>{const {outputText}=ts.transpileModule(readFileSync(new URL("../lib/"+name+".ts",import.meta.url),"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});const mod={exports:{}};new Function("module","exports","require",outputText)(mod,mod.exports,requireFn);return mod.exports;};
const matching=load("financial-reconciliation",()=>{throw Error("Unexpected import")});
const {detectFinancialDiscrepancies:detect}=load("financial-discrepancies",name=>{if(name==="./financial-reconciliation")return matching;throw Error("Unexpected import");});
const a={providerAccount:"a",transactionId:"t",kind:"collection",currency:"usd",amountMinor:100,status:"settled"};
const status=(p,l)=>detect(p,l)[0].status;
assert.deepEqual(detect([],[]),[]);
assert.equal(status([a],[a]),"matched");
assert.equal(status([a],[]),"missing_ledger");
assert.equal(status([],[a]),"missing_provider");
assert.equal(status([a,a],[a]),"duplicate");
assert.equal(status([a],[a,a]),"duplicate");
assert.equal(status([a,a],[]),"duplicate");
assert.equal(status([a],[{...a,amountMinor:99}]),"mismatch");
assert.equal(status([a],[{...a,currency:"eur"}]),"mismatch");
assert.equal(status([a],[{...a,status:"pending"}]),"mismatch");
const pending={...a,status:"pending"};
assert.equal(status([pending],[pending]),"pending");
assert.equal(detect([a],[{...a,providerAccount:"b"}]).length,2);
assert.equal(detect([a],[{...a,kind:"refund"}]).length,2);
assert.throws(()=>detect([],[{...a,amountMinor:-1}]));
assert.throws(()=>detect([{...a,transactionId:""}],[]));
assert.deepEqual(detect([a,a],[a])[0].providerCount,2);
console.log("16 financial discrepancy assertions passed");
