import assert from 'node:assert/strict';
import { issueAttemptToken } from './aff-attempt-token.mjs';
import { makeExamRpcAdapter } from './aff-secure-exam-rpc-adapter.mjs';
const token=issueAttemptToken().token;
let seen;
const submit=makeExamRpcAdapter(async(name,args)=>{seen={name,args};return {data:{ok:true,score:100,passed:true,result_id:7},error:null};});
const good=await submit({token,examId:'exam-1',answers:{q1:'a'},score:0,student_id:'forged'});
assert.equal(good.ok,true);
assert.equal(good.score,100);
assert.equal(seen.name,'aff_submit_secure_exam');
assert.deepEqual(Object.keys(seen.args).sort(),['p_answers','p_exam_id','p_token']);
assert.equal((await submit({token:'invalid',examId:'exam-1',answers:{}})).ok,false);
assert.equal((await submit({token,examId:'',answers:{}})).ok,false);
assert.equal((await submit({token,examId:'exam-1',answers:[]})).ok,false);
assert.equal((await submit({token,examId:'exam-1',answers:{q1:1}})).ok,false);
const failed=makeExamRpcAdapter(async()=>({error:{message:'secret'}}));
assert.equal((await failed({token,examId:'exam-1',answers:{}})).code,'SUBMISSION_FAILED');
assert.throws(()=>makeExamRpcAdapter(null),/Trusted RPC/);
console.log('PASS: offline exam RPC adapter assertions (mock only)');
